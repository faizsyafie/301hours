export function defaultTopics() {
  return Object.entries(LEVELS).flatMap(([level, topics]) =>
    topics.map(([id, ticker, name, weight, modules, pathway], i) => ({
      id, ticker, name, weight, level: Number(level), pathway: pathway || '', o: Number(level) * 100 + i, u: 0,
      items: modules.map((m, j) => ({ id: `${id}-${j + 1}`, name: m, o: j, done: false, doneAt: null, u: 0 })),
    })));
}

